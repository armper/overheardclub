-- Overheard Club schema. Written to run on both H2 (PostgreSQL mode) and PostgreSQL.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(50)  NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_app_user_username UNIQUE (username),
    CONSTRAINT uk_app_user_email UNIQUE (email)
);

CREATE TABLE topic (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(80) NOT NULL,
    created_by_id BIGINT NOT NULL REFERENCES app_user (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_topic_title UNIQUE (title)
);

CREATE TABLE post (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(80)   NOT NULL,
    content    VARCHAR(4096) NOT NULL,
    author_id  BIGINT NOT NULL REFERENCES app_user (id),
    topic_id   BIGINT NOT NULL REFERENCES topic (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_post_topic ON post (topic_id);
CREATE INDEX ix_post_created ON post (created_at);

CREATE TABLE comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content    VARCHAR(4096) NOT NULL,
    post_id    BIGINT NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    author_id  BIGINT NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_comment_post ON comment (post_id);

CREATE TABLE reaction (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES app_user (id),
    type       VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reaction_post_user UNIQUE (post_id, user_id)
);
CREATE INDEX ix_reaction_post ON reaction (post_id);
